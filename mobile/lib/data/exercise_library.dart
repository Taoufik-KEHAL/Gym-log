bool isKnownExerciseName(String name, {required bool cardio}) {
  final lname = name.toLowerCase();
  if (cardio) {
    return exerciseLibrary['Cardio']!.any((n) => n.toLowerCase() == lname);
  }
  return exerciseLibrary.entries
      .where((e) => e.key != 'Cardio')
      .any((e) => e.value.any((n) => n.toLowerCase() == lname));
}
